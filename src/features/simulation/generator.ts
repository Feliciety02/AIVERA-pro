/**
 * Pure, deterministic generator for SIMULATED scan output.
 *
 * Given a scan configuration and its target, it picks finding templates that
 * match the selected tools and categories (and the target's approved scope).
 * No network activity happens here or anywhere else in the frontend, this
 * only fabricates clearly-labelled demo records in memory.
 */
import type { DnsRecord, Endpoint, Evidence, Host, Port, Scan, ScanResult, Target, VulnerabilityFinding } from "@/types";
import { FINDING_TEMPLATES } from "@/data/findingTemplates";
import { TOOL_META } from "@/lib/constants";

export interface SimulationOutput {
  findings: VulnerabilityFinding[];
  evidence: Evidence[];
  results: ScanResult[];
  hosts: Host[];
  ports: Port[];
  dns: DnsRecord[];
  endpoints: Endpoint[];
}

function hash(input: string): number {
  let h = 0;
  for (let i = 0; i < input.length; i++) h = (h * 31 + input.charCodeAt(i)) >>> 0;
  return h;
}

/** Simple scope path matcher: "/api/*" matches "/api/x"; exact paths match themselves. */
export function pathMatches(pattern: string, path: string): boolean {
  if (pattern.endsWith("*")) return path.startsWith(pattern.slice(0, -1));
  return path === pattern || path.startsWith(pattern.endsWith("/") ? pattern : `${pattern}/`);
}

export function hostOf(url: string): string {
  try {
    return new URL(url).hostname;
  } catch {
    return url.replace(/^https?:\/\//, "").split("/")[0] ?? url;
  }
}

export const SIMULATION_STAGES = [
  { at: 0, label: "Validating approved scope (client-side demo check)" },
  { at: 12, label: "Loading tool profiles" },
  { at: 30, label: "Generating simulated discovery records" },
  { at: 55, label: "Generating simulated findings" },
  { at: 80, label: "Attaching synthetic evidence" },
  { at: 95, label: "Collating simulated results" },
];

export function stageFor(progress: number): string {
  let label = SIMULATION_STAGES[0]!.label;
  for (const s of SIMULATION_STAGES) if (progress >= s.at) label = s.label;
  return label;
}

export function generateSimulation(scan: Scan, target: Target, startIndex: number, assessorId: string, now: string): SimulationOutput {
  const host = hostOf(target.url);
  const tools = scan.config.tools;
  const allowedCats = scan.config.categories.filter((c) => target.scope.allowedCategories.includes(c));

  const excluded = scan.config.respectExclusions ? target.scope.excludedPaths : [];
  const candidates = FINDING_TEMPLATES.filter(
    (t) => t.sourceTool !== "manual" && tools.includes(t.sourceTool) && allowedCats.includes(t.category) && !excluded.some((p) => pathMatches(p, t.path)),
  );
  // Round-robin across categories (rotated deterministically per target/scan) so a
  // simulation covers several categories instead of clustering in one.
  const byCat = allowedCats.map((c) => candidates.filter((t) => t.category === c)).filter((g) => g.length);
  const offset = byCat.length ? hash(target.id + scan.id) % byCat.length : 0;
  const groups = [...byCat.slice(offset), ...byCat.slice(0, offset)];
  const interleaved: typeof candidates = [];
  for (let i = 0; groups.some((g) => g[i]); i++) groups.forEach((g) => g[i] && interleaved.push(g[i]!));
  const limit = scan.config.profile === "passive" ? 2 : scan.config.profile === "baseline" ? 3 : scan.config.profile === "standard" ? 5 : 6;
  const picked = interleaved.slice(0, limit);

  const findings: VulnerabilityFinding[] = [];
  const evidence: Evidence[] = [];
  picked.forEach((t, i) => {
    const id = `fnd-${scan.id}-${i + 1}`;
    findings.push({
      id,
      code: `FND-${String(startIndex + i).padStart(4, "0")}`,
      title: t.title,
      description: t.description,
      projectId: scan.projectId,
      targetId: target.id,
      scanId: scan.id,
      category: t.category,
      severity: t.severity,
      affectedAsset: t.path.startsWith("tcp/") ? `${host} ${t.path}` : `${target.url.replace(/\/$/, "")}${t.path}`,
      parameter: t.parameter,
      sourceTool: t.sourceTool,
      verificationStatus: "pending",
      signoffStatus: "not_required",
      assignedAssessorId: assessorId,
      discoveredAt: now,
      updatedAt: now,
      impact: t.impact,
      remediation: t.remediation,
      cwe: t.cwe,
      owasp: t.owasp,
      templateKey: t.key,
      dataOrigin: "simulated",
    });
    t.evidence.forEach((e, j) => {
      evidence.push({
        id: `ev-${id}-${j + 1}`,
        findingId: id,
        type: e.type,
        title: `${e.title} [SIMULATED]`,
        content: `# SIMULATED EVIDENCE, generated by the AIVERA demo simulation. No request was sent.\n${e.content.replaceAll("{host}", host)}`,
        source: t.sourceTool,
        capturedAt: now,
        reviewed: false,
        dataOrigin: "simulated",
      });
    });
  });

  const results: ScanResult[] = tools.map((tool) => {
    const fromTool = findings.filter((f) => f.sourceTool === tool);
    return {
      id: `sr-${scan.id}-${tool}`,
      scanId: scan.id,
      tool,
      summary: `SIMULATED: ${TOOL_META[tool].label} produced ${fromTool.length} sample finding(s)`,
      itemsFound: fromTool.length,
      rawOutput: `[SIMULATED OUTPUT, demo mode, no network activity]\ntool=${tool}\ntarget=${host}\nprofile=${scan.config.profile}\nrate_limit=${scan.config.requestsPerSecond}rps\nexcluded=${target.scope.excludedPaths.join(",") || "none"}\n${fromTool.map((f) => `- ${f.title} (${f.severity})`).join("\n") || "- no sample findings for this tool"}`,
      recordedAt: now,
      dataOrigin: "simulated",
    };
  });

  const hosts: Host[] = [];
  const ports: Port[] = [];
  if (tools.includes("nmap")) {
    const hostId = `hst-${scan.id}`;
    const octet = 50 + (hash(target.id) % 150);
    hosts.push({ id: hostId, targetId: target.id, scanId: scan.id, hostname: host, ipAddress: host === "localhost" ? "127.0.0.1" : `192.0.2.${octet}`, state: "up", osGuess: "Linux (simulated)", source: "nmap", observedAt: now, dataOrigin: "simulated" });
    [
      [443, "https", "nginx (simulated)"],
      [80, "http", "nginx (simulated)"],
      [22, "ssh", "OpenSSH (simulated)"],
    ].forEach(([p, svc, ver], i) =>
      ports.push({ id: `prt-${scan.id}-${i}`, hostId, port: p as number, protocol: "tcp", state: "open", service: svc as string, version: ver as string, source: "nmap", observedAt: now, dataOrigin: "simulated" }),
    );
  }
  const dns: DnsRecord[] = tools.includes("dns_utils")
    ? [{ id: `dns-${scan.id}`, targetId: target.id, name: host, type: "A", value: host === "localhost" ? "127.0.0.1" : "192.0.2.80", ttl: 300, source: "dns_utils", observedAt: now, dataOrigin: "simulated" }]
    : [];
  const endpoints: Endpoint[] = tools.includes("owasp_zap")
    ? findings
        .filter((f) => f.sourceTool === "owasp_zap")
        .map((f, i) => ({
          id: `ept-${scan.id}-${i}`,
          targetId: target.id,
          method: "GET" as const,
          path: f.affectedAsset.replace(target.url.replace(/\/$/, ""), "") || "/",
          statusCode: 200,
          contentType: "text/html",
          authRequired: false,
          source: "owasp_zap" as const,
          observedAt: now,
          dataOrigin: "simulated" as const,
        }))
    : [];

  return { findings, evidence, results, hosts, ports, dns, endpoints };
}
