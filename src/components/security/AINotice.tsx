import { Bot, FlaskConical } from "lucide-react";
import { Callout } from "@/components/shared/display";
import { useDataStore } from "@/stores/dataStore";

/**
 * Tells the user truthfully which AI is behind the analysis. Reads the
 * ai_service integration status reported by the server (API mode); in demo
 * mode it is always the predefined-sample adapter.
 */
export function AINotice() {
  const ai = useDataStore((s) => s.integrations.find((i) => i.id === "ai_service"));
  if (ai?.status === "connected")
    return (
      <Callout icon={Bot} title={`AI analysis via ${ai.integrationType.replace(/^Server-side /, "")}`}>
        Analyses are generated by a real AI model through the AIVERA server. Secrets (auth headers, cookies, tokens, passwords, keys, emails) are redacted before anything is sent, and you can inspect the exact data sent on each analysis. AI output is advisory: it can be wrong and never changes a finding's verification status. On the Gemini free tier, Google may use submitted content to improve its products, use test and synthetic data only.
      </Callout>
    );
  return (
    <Callout tone="demo" icon={FlaskConical} title="Sample AI Analysis, Demo Mode">
      No AI model is configured, so analyses come from a deterministic demo adapter that returns predefined samples linked to synthetic findings. To use real AI, run the full stack and set GEMINI_API_KEY in server/.env. AI output never changes the verification status.
    </Callout>
  );
}
