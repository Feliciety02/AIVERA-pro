import { Info } from "lucide-react";
import { Hint } from "@/components/ui/misc";
import { useDataStore } from "@/stores/dataStore";

/**
 * One quiet line saying which AI is behind the analysis, truthfully: the ai_service status the
 * server reports (API mode), or the predefined-sample adapter in demo mode. The detail sits in a
 * tooltip so it doesn't crowd the page.
 */
export function AINotice() {
  const ai = useDataStore((s) => s.integrations.find((i) => i.id === "ai_service"));
  const real = ai?.status === "connected";
  const detail = real
    ? "Generated by a real AI model through the AIVERA server. Secrets (auth headers, cookies, tokens, passwords, keys, emails) are removed before anything is sent. On the Gemini free tier, Google may use submitted content, so use test data only."
    : "No AI model is configured, so answers come from predefined samples. Set GEMINI_API_KEY in server/.env and run the full stack for real AI.";
  return (
    <p className="flex items-center gap-1.5 text-xs text-muted-foreground">
      {real ? "Real AI, secrets removed before sending." : "Demo mode: sample answers, not a real AI."} Advisory only; it never changes a finding's status.
      <Hint label={detail}>
        <span tabIndex={0} role="button" aria-label="More about the AI" className="text-muted-foreground/70 hover:text-foreground">
          <Info className="size-3.5" />
        </span>
      </Hint>
    </p>
  );
}
